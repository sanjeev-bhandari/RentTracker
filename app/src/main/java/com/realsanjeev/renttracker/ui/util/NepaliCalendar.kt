    // BS 1969-01-01 == AD 1912-04-12 (the year before the epoch)
    private val MIN_AD_DATE = LocalDate.of(1912, 4, 12)

    // First AD day beyond the supported range (== start of BS 2251)
    private val MAX_AD_EXCLUSIVE: LocalDate = AD_EPOCH.plusDays(
        (1970..MAX_BS_YEAR).sumOf { DATA[it - MIN_BS_YEAR][0].toLong() }
    )

    private val MONTH_NAMES = listOf(
        "Baishakh", "Jestha", "Ashadh", "Shrawan", "Bhadra", "Ashwin",
        "Kartik", "Mangsir", "Poush", "Magh", "Falgun", "Chaitra"
    )

    private val NEPALI_MONTH_NAMES = listOf(
        "बैशाख", "जेठ", "असार", "साउन", "भदौ", "असोज",
        "कात्तिक", "मंसिर", "पुष", "माघ", "फागुन", "चैत"
    )

    fun isSupportedYear(bsYear: Int): Boolean = bsYear in MIN_BS_YEAR..MAX_BS_YEAR

    fun daysInYear(bsYear: Int): Int = DATA[bsYear - MIN_BS_YEAR][0]

    fun daysInMonth(bsYear: Int, bsMonth: Int): Int {
        require(bsMonth in 1..12) { "Invalid BS month: $bsMonth" }
        return DATA[bsYear - MIN_BS_YEAR][bsMonth]
    }

    fun monthName(bsMonth: Int): String = MONTH_NAMES[bsMonth - 1]

    fun monthNameNepali(bsMonth: Int): String = NEPALI_MONTH_NAMES[bsMonth - 1]

    /** Converts an AD (Gregorian) date to a Bikram Sambat date. */
    fun toBs(ad: LocalDate): NepaliDate {
        require(!ad.isBefore(MIN_AD_DATE) && ad.isBefore(MAX_AD_EXCLUSIVE)) {
            "AD date $ad is outside the supported range ($MIN_AD_DATE to ${MAX_AD_EXCLUSIVE.minusDays(1)})"
        }
        var diff = ad.toEpochDay() - AD_EPOCH.toEpochDay()
        var bsYear = 1970
        // Dates before the epoch fall into BS 1969
        while (diff < 0) {
            bsYear--
            diff += daysInYear(bsYear)
        }
        while (diff >= daysInYear(bsYear)) {
            diff -= daysInYear(bsYear)
            bsYear++
        }
        var bsMonth = 1
        while (diff >= daysInMonth(bsYear, bsMonth)) {
            diff -= daysInMonth(bsYear, bsMonth)
            bsMonth++
        }
        return NepaliDate(bsYear, bsMonth, (diff + 1).toInt())
    }

    /** Converts a Bikram Sambat date to an AD (Gregorian) date. */
    fun toAd(bs: NepaliDate): LocalDate {
        require(isSupportedYear(bs.year)) {
            "BS year ${bs.year} is outside supported range ($MIN_BS_YEAR-$MAX_BS_YEAR)"
        }
        require(bs.month in 1..12) { "Invalid BS month: ${bs.month}" }
        require(bs.day in 1..daysInMonth(bs.year, bs.month)) {
            "Invalid BS day ${bs.day} for ${bs.year}-${bs.month}"
        }
        var totalDays = 0L
        for (year in 1970 until bs.year) totalDays += daysInYear(year)
        if (bs.year < 1970) totalDays -= daysInYear(1969)
        for (month in 1 until bs.month) totalDays += daysInMonth(bs.year, month)
        totalDays += bs.day - 1
        return AD_EPOCH.plusDays(totalDays)
    }
